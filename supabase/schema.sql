create table if not exists admin_users (
  id          integer generated by default as identity primary key,
  username    varchar(50)  not null unique,
  password    varchar(255) not null
);

create table if not exists settings (
  id            integer generated by default as identity primary key,
  setting_key   varchar(100) not null unique,
  setting_value text
);

create table if not exists products (
  id                integer generated by default as identity primary key,
  title             varchar(255),
  price             varchar(50),
  discount_price    varchar(50),
  image             text,
  badge             varchar(500),
  flash_sale        varchar(50),
  rating            varchar(10),
  sold              varchar(50),
  discount_percent  varchar(50),
  flash_sale_timer  varchar(50),
  flash_sale_title  varchar(255),
  flash_sale_text   varchar(255),
  bottom_bar_text   varchar(255),
  reviews_json      text,
  description       text,
  features          text,
  packing_list      text,
  ml_id             varchar(100),
  category          varchar(255),
  brand             varchar(255),
  sku               varchar(255),
  specifications    text,
  attributes        text,
  stock             varchar(50),
  sales_quantity    varchar(50),
  seo_title         varchar(255),
  seo_description   text,
  videos            text,
  variations        text,
  technical_data    text,
  related_products  text,
  total_reviews     varchar(50)
);

create table if not exists categories (
  id          integer generated by default as identity primary key,
  name        varchar(255) not null unique,
  image       varchar(500) default '',
  created_at  timestamp not null default (now() at time zone 'America/Sao_Paulo')
);

create table if not exists customers (
  id            integer generated by default as identity primary key,
  name          varchar(255),
  cpf           varchar(50),
  phone         varchar(50),
  email         varchar(255),
  cep           varchar(20),
  address       text,
  number        varchar(20),
  neighborhood  varchar(100),
  city          varchar(100),
  state         varchar(10),
  product_name  varchar(255),
  variation     varchar(255),
  note          text,
  reviews       text,
  reviews_json  text,
  status        varchar(20) default 'pendente',
  created_at    timestamp not null default (now() at time zone 'America/Sao_Paulo')
);

create table if not exists orders (
  id                 integer generated by default as identity primary key,
  customer_name      varchar(255),
  customer_document  varchar(50),
  customer_email     varchar(255),
  customer_phone     varchar(50),
  product_id         varchar(100),
  variation_id       varchar(100),
  option_id          varchar(100),
  size_id            varchar(100),
  variation          varchar(255),
  quantity           integer default 1,
  amount             numeric(10,2) default 0,
  status             varchar(50) default 'pending',
  payment_method     varchar(50) default 'pix',
  transaction_id     varchar(100),
  note               text,
  created_at         timestamp not null default (now() at time zone 'America/Sao_Paulo')
);

create table if not exists chat_messages (
  id          integer generated by default as identity primary key,
  session_id  varchar(100) not null,
  sender      varchar(20)  not null check (sender in ('customer','admin')),
  message     text not null,
  is_read     smallint default 0,
  created_at  timestamp not null default (now() at time zone 'America/Sao_Paulo')
);
create index if not exists idx_chat_session on chat_messages (session_id);

create table if not exists live_visitors (
  session_id   varchar(100) primary key,
  page         varchar(50),
  last_active  timestamp not null default (now() at time zone 'America/Sao_Paulo'),
  created_at   timestamp not null default (now() at time zone 'America/Sao_Paulo')
);

-- Sessoes PHP (o login do admin precisa persistir entre invocacoes serverless)
create table if not exists php_sessions (
  id          varchar(128) primary key,
  data        text not null default '',
  updated_at  timestamp not null default (now() at time zone 'America/Sao_Paulo')
);

-- Seguranca: todo acesso e feito pelo backend com a conexao direta do Postgres.
-- Ativa RLS sem policies => a API publica (anon key) NAO consegue ler/escrever nada.
alter table admin_users    enable row level security;
alter table settings       enable row level security;
alter table products       enable row level security;
alter table categories     enable row level security;
alter table customers      enable row level security;
alter table orders         enable row level security;
alter table chat_messages  enable row level security;
alter table live_visitors  enable row level security;
alter table php_sessions   enable row level security;

